# HEADER
# ------------------------------------------------------------

st.title("🩺 GlucoTwin AI")
st.subheader("Personalized Digital Twin for Early Glucose Spike Prediction")

st.info(
    "Proof-of-concept AI system using synthetic EHR and wearable data "
    "to estimate the risk of a glucose spike within the next 2 hours."
)

st.divider()


# ------------------------------------------------------------
# SIDEBAR - PATIENT PROFILE
# ------------------------------------------------------------

st.sidebar.header("👤 Patient Profile")

age = st.sidebar.slider(
    "Age",
    min_value=18,
    max_value=90,
    value=50
)

gender = st.sidebar.selectbox(
    "Gender",
    ["Female", "Male"]
)

bmi = st.sidebar.number_input(
    "BMI",
    min_value=15.0,
    max_value=50.0,
    value=27.0,
    step=0.1
)

hba1c = st.sidebar.number_input(
    "HbA1c (%)",
    min_value=3.0,
    max_value=15.0,
    value=6.5,
    step=0.1
)

systolic_bp = st.sidebar.number_input(
    "Systolic BP",
    min_value=80,
    max_value=220,
    value=135
)

diabetes_history = st.sidebar.selectbox(
    "Diabetes History",
    [0, 1],
    format_func=lambda x: "Yes" if x == 1 else "No"
)

family_history = st.sidebar.selectbox(
    "Family History",
    [0, 1],
    format_func=lambda x: "Yes" if x == 1 else "No"
)


# ------------------------------------------------------------
# WEARABLE DATA
# ------------------------------------------------------------

st.sidebar.header("⌚ Wearable Data")

glucose = st.sidebar.number_input(
    "Current Glucose (mg/dL)",
    min_value=50.0,
    max_value=300.0,
    value=120.0,
    step=0.1
)

heart_rate = st.sidebar.number_input(
    "Heart Rate (BPM)",
    min_value=40.0,
    max_value=180.0,
    value=72.0,
    step=1.0
)

steps = st.sidebar.number_input(
    "Current Steps",
    min_value=0,
    max_value=30000,
    value=850
)

sleep_hours = st.sidebar.slider(
    "Sleep (hours)",
    min_value=0.0,
    max_value=12.0,
    value=6.5,
    step=0.5
)


# ------------------------------------------------------------
# TIME-SERIES INPUTS
# ------------------------------------------------------------

st.sidebar.header("📈 Recent Trends")

glucose_change_1h = st.sidebar.number_input(
    "Glucose Change - 1h",
    value=0.0,
    step=0.1
)

glucose_change_2h = st.sidebar.number_input(
    "Glucose Change - 2h",
    value=0.0,
    step=0.1
)

glucose_rolling_3h = st.sidebar.number_input(
    "3h Average Glucose",
    value=float(glucose),
    step=0.1
)

glucose_rolling_std_3h = st.sidebar.number_input(
    "3h Glucose Variability",
    min_value=0.0,
    value=5.0,
    step=0.1
)

heart_rate_change_1h = st.sidebar.number_input(
    "Heart Rate Change - 1h",
    value=0.0,
    step=0.1
)

steps_rolling_3h = st.sidebar.number_input(
    "Steps - Last 3h",
    min_value=0,
    max_value=30000,
    value=1500
)


# ------------------------------------------------------------
# TIME
# ------------------------------------------------------------

current_hour = datetime.now().hour
day_of_week = datetime.now().weekday()


# ------------------------------------------------------------
# MAIN DASHBOARD
# ------------------------------------------------------------

st.header("📊 Current Patient Status")

col1, col2, col3, col4 = st.columns(4)

with col1:
    st.metric(
        "Glucose",
        f"{glucose:.1f} mg/dL"
    )

with col2:
    st.metric(
        "Heart Rate",
        f"{heart_rate:.0f} BPM"
    )

with col3:
    st.metric(
        "Steps",
        f"{steps:,}"
    )

with col4:
    st.metric(
        "Sleep",
        f"{sleep_hours:.1f} hrs"
    )


st.divider()


# ------------------------------------------------------------
# PREDICTION
# ------------------------------------------------------------

st.header("🔮 Digital Twin Prediction")

if st.button(
    "🚀 Predict 2-Hour Glucose Spike Risk",
    use_container_width=True
):

    input_data = pd.DataFrame([{
        "glucose": glucose,
        "heart_rate": heart_rate,
        "steps": steps,
        "sleep_hours": sleep_hours,
        "age": age,
        "gender": gender,
        "bmi": bmi,
        "hba1c": hba1c,
        "systolic_bp": systolic_bp,
        "diabetes_history": diabetes_history,
        "family_history": family_history,
        "hour": current_hour,
        "day_of_week": day_of_week,
        "glucose_change_1h": glucose_change_1h,
        "glucose_change_2h": glucose_change_2h,
        "glucose_rolling_3h": glucose_rolling_3h,
        "glucose_rolling_std_3h": glucose_rolling_std_3h,
        "heart_rate_change_1h": heart_rate_change_1h,
        "steps_rolling_3h": steps_rolling_3h
    }])

    prediction = model.predict(input_data)[0]

    probability = model.predict_proba(
        input_data
    )[0][1]

    probability_percent = probability * 100


    # --------------------------------------------------------
    # RISK LEVEL
    # --------------------------------------------------------

    if probability >= 0.70:
        risk = "HIGH"
    elif probability >= 0.40:
        risk = "MEDIUM"
    else:
        risk = "LOW"


    # --------------------------------------------------------
    # DISPLAY RESULT
    # --------------------------------------------------------

    st.subheader("Prediction Result")

    result_col1, result_col2 = st.columns(2)

    with result_col1:

        if risk == "HIGH":
            st.error(
                "🔴 HIGH RISK\n\n"
                "Potential glucose spike within the next 2 hours."
            )

        elif risk == "MEDIUM":
            st.warning(
                "🟡 MEDIUM RISK\n\n"
                "Moderate probability of a glucose spike."
            )

        else:
            st.success(
                "🟢 LOW RISK\n\n"
                "Low predicted probability of a glucose spike."
            )

    with result_col2:

        st.metric(
            "Spike Probability",
            f"{probability_percent:.1f}%"
        )

        st.progress(
            min(probability, 1.0)
        )


    # --------------------------------------------------------
    # DIGITAL TWIN SUMMARY
    # --------------------------------------------------------

    st.divider()

    st.subheader("🧬 Digital Twin Summary")

    summary_col1, summary_col2, summary_col3 = st.columns(3)

    with summary_col1:
        st.write("**Patient Profile**")
        st.write(f"Age: {age}")
        st.write(f"BMI: {bmi}")
        st.write(f"HbA1c: {hba1c}%")

    with summary_col2:
        st.write("**Wearable Signals**")
        st.write(f"Glucose: {glucose:.1f} mg/dL")
        st.write(f"Heart Rate: {heart_rate:.0f} BPM")
        st.write(f"Steps: {steps:,}")

    with summary_col3:
        st.write("**Recent Trends**")
        st.write(f"1h Glucose Change: {glucose_change_1h:.1f}")
        st.write(f"2h Glucose Change: {glucose_change_2h:.1f}")
        st.write(f"3h Steps: {steps_rolling_3h:,}")


    # --------------------------------------------------------
    # IMPORTANT FACTORS
    # --------------------------------------------------------

    st.divider()

    st.subheader("🔍 Important Prediction Signals")

    factors = []

    if glucose_change_2h > 15:
        factors.append(
            "📈 Glucose has increased significantly over the last 2 hours."
        )

    if glucose_change_1h > 10:
        factors.append(
            "📈 Glucose is rising rapidly over the last hour."
        )

    if glucose > 140:
        factors.append(
            "🩸 Current glucose level is elevated."
        )

    if sleep_hours < 5:
        factors.append(
            "😴 Low sleep duration may contribute to metabolic risk."
        )

    if steps_rolling_3h < 500:
        factors.append(
            "🚶 Low recent physical activity."
        )

    if hba1c >= 6.5:
        factors.append(
            "🧪 HbA1c indicates elevated long-term glucose levels."
        )

    if not factors:
        factors.append(
            "✅ No major rule-based risk signals detected."
        )

    for factor in factors:
        st.write(factor)


