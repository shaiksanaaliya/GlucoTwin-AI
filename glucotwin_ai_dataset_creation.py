import pandas as pd
import numpy as np

# Reproducibility
np.random.seed(42)

# ============================================================
# STEP 1: CREATE SYNTHETIC EHR DATA
# ============================================================

num_patients = 500

patient_ids = [
    f"P{str(i).zfill(4)}"
    for i in range(1, num_patients + 1)
]

ehr_data = pd.DataFrame({
    "patient_id": patient_ids,

    "age": np.random.randint(
        30, 71, num_patients
    ),

    "gender": np.random.choice(
        ["Male", "Female"],
        num_patients
    ),

    "bmi": np.round(
        np.random.normal(27, 4, num_patients),
        1
    ),

    "hba1c": np.round(
        np.random.normal(6.2, 0.8, num_patients),
        1
    ),

    "systolic_bp": np.random.randint(
        110, 161, num_patients
    ),

    "diabetes_history": np.random.choice(
        [0, 1],
        num_patients,
        p=[0.45, 0.55]
    ),

    "family_history": np.random.choice(
        [0, 1],
        num_patients,
        p=[0.40, 0.60]
    )
})

# Keep values realistic
ehr_data["bmi"] = ehr_data["bmi"].clip(18, 40)

ehr_data["hba1c"] = ehr_data["hba1c"].clip(
    4.5, 10
)

# ============================================================
# STEP 2: CREATE SYNTHETIC WEARABLE DATA
# ============================================================

days = 7
hours_per_day = 24

wearable_records = []

for _, patient in ehr_data.iterrows():

    # Patient-specific baseline glucose
    baseline_glucose = (
        95
        + (patient["hba1c"] - 5.5) * 18
        + (patient["bmi"] - 25) * 1.5
        + patient["diabetes_history"] * 8
    )

    for day in range(days):

        # Sleep is treated as the previous night's sleep
        sleep_hours = np.random.normal(
            6.5, 1.2
        )

        sleep_hours = np.clip(
            sleep_hours,
            4,
            9
        )

        for hour in range(hours_per_day):

            timestamp = (
                pd.Timestamp("2026-01-01")
                + pd.Timedelta(
                    days=day,
                    hours=hour
                )
            )

            # ------------------------------------------------
            # ACTIVITY / STEPS
            # ------------------------------------------------

            if 7 <= hour <= 9:

                steps = np.random.randint(
                    300,
                    1800
                )

            elif 10 <= hour <= 18:

                steps = np.random.randint(
                    200,
                    1500
                )

            elif 19 <= hour <= 21:

                steps = np.random.randint(
                    300,
                    1200
                )

            else:

                steps = np.random.randint(
                    20,
                    500
                )

            # ------------------------------------------------
            # HEART RATE
            # ------------------------------------------------

            heart_rate = (
                65
                + (steps / 120)
                + np.random.normal(0, 4)
            )

            heart_rate = np.clip(
                heart_rate,
                55,
                130
            )

            # ------------------------------------------------
            # MEAL EFFECT
            # ------------------------------------------------

            meal_effect = 0

            # Breakfast
            if 7 <= hour <= 9:

                meal_effect += np.random.uniform(
                    10,
                    35
                )

            # Lunch
            if 12 <= hour <= 14:

                meal_effect += np.random.uniform(
                    15,
                    45
                )

            # Dinner
            if 19 <= hour <= 21:

                meal_effect += np.random.uniform(
                    15,
                    40
                )

            # ------------------------------------------------
            # HEALTH RISK EFFECTS
            # ------------------------------------------------

            diabetes_effect = (
                patient["diabetes_history"]
                * np.random.uniform(5, 20)
            )

            poor_sleep_effect = (
                max(0, 6 - sleep_hours)
                * np.random.uniform(2, 6)
            )

            low_activity_effect = (
                max(0, 500 - steps) / 100
            )

            high_hr_effect = (
                max(0, heart_rate - 85)
                * 0.4
            )

            # ------------------------------------------------
            # GLUCOSE
            # ------------------------------------------------

            glucose = (
                baseline_glucose
                + meal_effect
                + diabetes_effect
                + poor_sleep_effect
                + low_activity_effect
                + high_hr_effect
                + np.random.normal(0, 7)
            )

            glucose = np.clip(
                glucose,
                70,
                280
            )

            wearable_records.append({

                "patient_id":
                    patient["patient_id"],

                "timestamp":
                    timestamp,

                "glucose":
                    round(glucose, 1),

                "heart_rate":
                    round(heart_rate, 1),

                "steps":
                    int(steps),

                "sleep_hours":
                    round(sleep_hours, 1)
            })


# Convert wearable records to DataFrame
wearable_data = pd.DataFrame(
    wearable_records
)

# Sort
wearable_data = wearable_data.sort_values(
    ["patient_id", "timestamp"]
).reset_index(drop=True)

# ============================================================
# STEP 3: CREATE 2-HOUR FUTURE GLUCOSE
# ============================================================

wearable_data["glucose_2h_future"] = (

    wearable_data
    .groupby("patient_id")["glucose"]
    .shift(-2)
)

# ============================================================
# STEP 4: CREATE TARGET
# ============================================================

# Target:
# 1 = glucose increases by at least 25 mg/dL
#     within the next 2 hours
#
# 0 = otherwise

wearable_data["glucose_spike"] = (

    wearable_data["glucose_2h_future"]
    >= wearable_data["glucose"] + 25

).astype(int)

# Remove rows where future glucose doesn't exist
wearable_data = wearable_data.dropna(
    subset=["glucose_2h_future"]
).reset_index(drop=True)

# ============================================================
# STEP 5: MERGE EHR + WEARABLE DATA
# ============================================================

combined_data = wearable_data.merge(
    ehr_data,
    on="patient_id",
    how="left"
)

